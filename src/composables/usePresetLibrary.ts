// Plain module-level reactive singleton (no Pinia -- see
// docs/ARCHITECTURE.md / approved plan's stack-discipline note).
// Loads the bank manifest, then a specific bank's JSON on demand. Also
// merges in Sound Design (user-created, IndexedDB-backed) banks so
// Performance mode's BankSelector can list and play them alongside the
// built-in static banks -- see approved plan Part 3 / M11.
import { ref, shallowRef, computed } from 'vue'
import type { Bank, BankManifest, BankManifestEntry } from '../core/audio/types'
import { useUserBanks } from './useUserBanks'

const manifest = ref<BankManifestEntry[]>([])
const currentBank = shallowRef<Bank | null>(null)
const currentBankId = ref<string | null>(null)
const loading = ref(false)
const error = ref<string | null>(null)

const { banks: userBanks, refresh: refreshUserBanks } = useUserBanks()

/** Static manifest entries + user banks, both tagged by `source`, for
 * BankSelector to list and group. */
const combinedManifest = computed<BankManifestEntry[]>(() => [
  ...manifest.value.map((b) => ({ ...b, source: 'static' as const })),
  ...userBanks.value.map((b) => ({
    id: b.id,
    name: b.name,
    presetCount: Object.keys(b.bank.presets).length,
    schemaVersion: b.bank._meta.schemaVersion,
    source: 'user' as const,
  })),
])

// no-store: this JSON is regenerated by tools/build_bank.py during active
// development, and a stale cached copy silently masking fixes was a real
// source of confusion during troubleshooting -- always hit the network.
async function loadManifest(): Promise<BankManifestEntry[]> {
  const res = await fetch('/data/banks/manifest.json', { cache: 'no-store' })
  if (!res.ok) throw new Error(`manifest.json: HTTP ${res.status}`)
  const data: BankManifest = await res.json()
  manifest.value = data.banks
  await refreshUserBanks()
  return combinedManifest.value
}

async function loadBank(bankId: string): Promise<Bank> {
  loading.value = true
  error.value = null
  try {
    // User bank: already in memory (IndexedDB-backed reactive record), no
    // fetch needed -- load it directly.
    const userRecord = userBanks.value.find((b) => b.id === bankId)
    if (userRecord) {
      currentBank.value = userRecord.bank
      currentBankId.value = bankId
      return userRecord.bank
    }

    const res = await fetch(`/data/banks/${bankId}/bank.json`, { cache: 'no-store' })
    if (!res.ok) throw new Error(`bank.json (${bankId}): HTTP ${res.status}`)
    const bank: Bank = await res.json()
    currentBank.value = bank
    currentBankId.value = bankId
    return bank
  } catch (e) {
    error.value = e instanceof Error ? e.message : String(e)
    throw e
  } finally {
    loading.value = false
  }
}

export function usePresetLibrary() {
  return { manifest: combinedManifest, currentBank, currentBankId, loading, error, loadManifest, loadBank }
}
